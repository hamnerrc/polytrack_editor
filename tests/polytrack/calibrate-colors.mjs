// Measures what every pixel-art "colour" really looks like in the game.
//
// For each environment (Summer / Winter / Desert) a swatch track is generated with the editor's own
// encoder, imported into the real game and rendered straight from above. The on-screen colour of
// every swatch (each block type × block colour, plus bare ground) is sampled from a screenshot and
// written to js/pixel-palette.js, which the editor's Pixel Art mode uses for colour matching.
//
// Usage: node calibrate-colors.mjs
import fs from 'node:fs';
import path from 'node:path';
import { launch, openTool, openGame, importTrack, topDownShot, samplePixels, OUT, UNIT_M } from './lib.mjs';

const ENVIRONMENTS = ['Summer', 'Winter', 'Desert'];
// Flat, single-colour, 4×4-unit parts and the colour ids each supports (from the game's part table)
const CANDIDATES = [
  ...[1, 2, 3, 32, 33, 34, 35, 36, 37, 38, 39, 40].map(color => ({ id: 29, color })),  // Block
  ...[1, 2, 3].map(color => ({ id: 25, color })),                                        // Plane (road surface)
];
const COLS = 4, SW = 3, PITCH = 6;   // swatch = 3×3 blocks, 6 blocks apart → ground visible in between

const swatchPos = i => ({ cx: (i % COLS) * PITCH * 4, cz: Math.floor(i / COLS) * PITCH * 4 });

const browser = await launch();
const game = await openGame(browser);
const tool = await openTool(browser);
const palette = {};

for (let env = 0; env < ENVIRONMENTS.length; env++) {
  // Swatch track built with the editor's real encoder (so block colours / environment are tested too)
  const code = await tool.evaluate(async (cands, env, COLS, SW, PITCH) => {
    const lines = cands.map((c, i) => {
      const cx = (i % COLS) * PITCH * 4, cz = Math.floor(i / COLS) * PITCH * 4, points = [];
      for (let a = 0; a < SW; a++) for (let b = 0; b < SW; b++) points.push({ x: cx + (a - 1) * 4, y: 0, z: cz + (b - 1) * 4 });
      return { id: c.id, rot: 0, color: c.color, points };
    });
    lines.push({ id: 92, rot: 0, points: [{ x: -80, y: 0, z: -80 }] });   // start, well away from the swatches
    return encodeTrack(lines, 'palette calibration ' + env, 'tests', env);
  }, CANDIDATES, env, COLS, SW, PITCH);

  await importTrack(game, code);
  // decoded coordinates are shifted so the minimum is 0; the start block was placed at (-80, -80)
  const shift = await game.evaluate(code => {
    let s = null;
    window.__pt.Track.fromExportString(code).trackData.forEachPart((x, y, z, id) => { if (id === 92) s = [x + 80, z + 80]; });
    return s;
  }, code);
  const rows = Math.ceil((CANDIDATES.length + 1) / COLS);
  const view = await topDownShot(game, {
    cxM: ((COLS - 1) * PITCH * 4 / 2 + shift[0]) * UNIT_M, czM: ((rows - 1) * PITCH * 4 / 2 + shift[1]) * UNIT_M,
    file: `palette-${ENVIRONMENTS[env].toLowerCase()}.png`,
  });
  const img = view.img;
  const proj = [...CANDIDATES.map((_, i) => swatchPos(i)), swatchPos(CANDIDATES.length)]
    .map(p => view.toScreen((p.cx + shift[0]) * UNIT_M, (p.cz + shift[1]) * UNIT_M));

  palette[ENVIRONMENTS[env]] = CANDIDATES.map((c, i) => ({ ...c, ...samplePixels(img, proj[i][0], proj[i][1], 14) }));
  // bare ground: the empty swatch slot after the last candidate
  const g = samplePixels(img, proj[CANDIDATES.length][0], proj[CANDIDATES.length][1], 14);
  palette[ENVIRONMENTS[env]].push({ id: null, color: 0, ...g });
  console.log(ENVIRONMENTS[env]);
  for (const p of palette[ENVIRONMENTS[env]]) console.log(`  ${p.id === null ? 'ground  ' : `id ${p.id} c${String(p.color).padEnd(2)}`}  rgb(${p.rgb.join(',')})  spread ${p.spread}`);
}
await browser.close();

if (!process.argv.includes('--dry')) {
  const js = `'use strict';
// GENERATED by tests/polytrack/calibrate-colors.mjs - do not edit by hand.
// On-screen colour (sRGB, lit, seen from above) of every flat single-colour block in the real game,
// per environment. id null = no block (bare ground). Block 29 = "Block", 25 = "Plane".
const PIXEL_PALETTE = ${JSON.stringify(Object.fromEntries(Object.entries(palette).map(([k, v]) => [k, v.map(({ id, color, rgb }) => ({ id, color, rgb }))])), null, 1).replace(/\n\s+(?=[\d"\]}]|id|color|rgb)/g, ' ').replace(/\[ /g, '[').replace(/ \]/g, ']')};
`;
  fs.writeFileSync(path.resolve(OUT, '../../../js/pixel-palette.js'), js);
  console.log('wrote js/pixel-palette.js');
}
